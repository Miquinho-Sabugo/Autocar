-- 1. TABELA DE USUÁRIOS (Sistema de Contas Independente)
CREATE TABLE IF NOT EXISTS usuarios (
    id BIGSERIAL PRIMARY KEY,
    nome TEXT NOT NULL,
    email TEXT UNIQUE NOT NULL,
    senha TEXT NOT NULL,
    cpf TEXT UNIQUE,
    telefone TEXT,
    tipo TEXT DEFAULT 'cliente' CHECK (tipo IN ('cliente', 'administrador')),
    criado_em TIMESTAMPTZ DEFAULT now() NOT NULL
);

-- 2. TABELA DE VEÍCULOS (Estoque com preços de mercado)
CREATE TABLE IF NOT EXISTS veiculos (
    id BIGSERIAL PRIMARY KEY,
    titulo TEXT NOT NULL,
    categoria TEXT NOT NULL CHECK (categoria IN ('Sedan', 'SUV', 'Hatch', 'Pickup', 'Esportivo', 'Elétrico')),
    preco NUMERIC(12, 2) NOT NULL,
    ano INT NOT NULL,
    km INT NOT NULL,
    cambio TEXT NOT NULL,
    combustivel TEXT NOT NULL,
    placa TEXT UNIQUE NOT NULL,
    cor TEXT NOT NULL,
    laudo_cautelar_aprovado BOOLEAN DEFAULT TRUE,
    badge TEXT DEFAULT 'Destaque',
    rating NUMERIC(3, 1) DEFAULT 4.8,
    reviews_count INT DEFAULT 50,
    descricao TEXT,
    imagem_url TEXT,
    status TEXT DEFAULT 'disponivel' CHECK (status IN ('disponivel', 'reservado', 'vendido')),
    criado_em TIMESTAMPTZ DEFAULT now() NOT NULL
);

-- 3. TABELA DE RESERVAS E COMPRAS ONLINE
CREATE TABLE IF NOT EXISTS reservas (
    id BIGSERIAL PRIMARY KEY,
    codigo_reserva TEXT UNIQUE NOT NULL,
    usuario_id BIGINT REFERENCES usuarios(id) ON DELETE SET NULL,
    nome_cliente TEXT NOT NULL,
    cpf_cliente TEXT NOT NULL,
    telefone_cliente TEXT NOT NULL,
    cep_entrega TEXT,
    tipo_retirada TEXT DEFAULT 'store',
    veiculo_id BIGINT REFERENCES veiculos(id) ON DELETE CASCADE NOT NULL,
    valor_reserva NUMERIC(12, 2) NOT NULL,
    metodo_pagamento TEXT NOT NULL CHECK (metodo_pagamento IN ('pix', 'cartao', 'boleto')),
    status_pagamento TEXT DEFAULT 'aprovado' CHECK (status_pagamento IN ('pendente', 'aprovado', 'cancelado')),
    criado_em TIMESTAMPTZ DEFAULT now() NOT NULL
);

-- 4. TABELA DE PROPOSTAS DE TROCA DE VEÍCULOS
CREATE TABLE IF NOT EXISTS propostas_troca (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    usuario_id BIGINT REFERENCES usuarios(id) ON DELETE SET NULL,
    nome_cliente TEXT,
    telefone_cliente TEXT,
    veiculo_desejado_id BIGINT REFERENCES veiculos(id) ON DELETE CASCADE NOT NULL,
    meu_carro_modelo TEXT NOT NULL,
    meu_carro_placa TEXT NOT NULL,
    meu_carro_ano INT NOT NULL,
    meu_carro_km INT NOT NULL,
    estado_conservacao TEXT NOT NULL,
    valor_proposta NUMERIC(12, 2),
    status TEXT DEFAULT 'em_analise' CHECK (status IN ('em_analise', 'aprovada', 'recusada')),
    criado_em TIMESTAMPTZ DEFAULT now() NOT NULL
);

-- 5. TABELAS DE FAVORITOS E IMAGENS VINCULADAS A USUÁRIOS E VEÍCULOS
CREATE TABLE IF NOT EXISTS favoritos (
    id BIGSERIAL PRIMARY KEY,
    usuario_id BIGINT REFERENCES usuarios(id) ON DELETE CASCADE NOT NULL,
    veiculo_id BIGINT REFERENCES veiculos(id) ON DELETE CASCADE NOT NULL,
    criado_em TIMESTAMPTZ DEFAULT now() NOT NULL,
    UNIQUE(usuario_id, veiculo_id)
);

CREATE TABLE IF NOT EXISTS veiculos_imagens (
    id BIGSERIAL PRIMARY KEY,
    veiculo_id BIGINT REFERENCES veiculos(id) ON DELETE CASCADE,
    imagem_dado TEXT NOT NULL,
    criado_em TIMESTAMPTZ DEFAULT now() NOT NULL
);

CREATE TABLE IF NOT EXISTS usuarios_imagens (
    usuario_id BIGINT PRIMARY KEY REFERENCES usuarios(id) ON DELETE CASCADE,
    imagem_dado TEXT NOT NULL,
    atualizado_em TIMESTAMPTZ DEFAULT now() NOT NULL
);

